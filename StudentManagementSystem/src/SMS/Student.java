package SMS;

public class Student {
	String name;
	int age;
	
	public Student(String name, int age){
		this.name = name;
		this.age = age;
	}
	public void setname(String name) {
		this.name = name;
	}
	public void setnage(int age) {
		this.age = age;
	}
	public void getname(String name) {
		this.name = name;
	}
	public void getage(int age) {
		this.age = age;
	}
}
